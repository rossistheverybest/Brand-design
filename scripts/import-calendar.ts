// Converts the artifact calendar snapshot into supabase/seed.sql (brands,
// week themes, calendar items). Re-runnable: items are keyed on
// (brand, date, title) and skipped if they already exist.
//   npm run import:calendar
import { writeFileSync } from "node:fs";
import { DEFAULT_KITS } from "../src/lib/brand";
import { FACTS, ITEMS, NOTES, THEMES } from "../data/artifact-calendar";

const BRAND: Record<string, string> = { corvus: "corvus", winter: "winterstoke", altus: "altus" };
const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

function classify(i: (typeof ITEMS)[number]) {
  if (i.kind !== "post") return { kind: i.kind, format: "none", pillar: null as string | null, brief: i.m ?? null };
  const [a, b] = (i.m ?? "").split(" · ").map((s) => s?.trim());
  if (i.b === "corvus") {
    // Corvus meta is "<photo> · <status>"
    const carousel = /carousel/i.test(i.t);
    const photo = a && !["rendered", "planned", "cancelled"].includes(a) ? a : null;
    return {
      kind: "post", format: carousel ? "carousel" : "single",
      pillar: i.t === "Inspiration" ? "Inspiration" : null,
      brief: [photo ? `Planned photo: ${photo}.` : null, b === "rendered" || a === "rendered" ? "A version was already made outside Brand Studio." : null].filter(Boolean).join(" ") || null,
    };
  }
  // Altus meta is "<pillar> · <format>"
  const fmt = (b ?? "").toLowerCase();
  const format = fmt.includes("carousel") ? "carousel" : fmt === "reel" ? "reel" : fmt === "stories" ? "story" : "single";
  return { kind: format === "story" ? "story" : "post", format, pillar: a || null, brief: fmt.includes("stories + post") ? "Feed post plus live stories on the day." : null };
}

let sql = "-- Generated by scripts/import-calendar.ts from the Altus Marketing Calendar artifact.\n\n";
for (const [id, { name, kit }] of Object.entries(DEFAULT_KITS)) {
  sql += `insert into brands (id, name, kit) values (${q(id)}, ${q(name)}, ${q(JSON.stringify(kit))}::jsonb) on conflict (id) do nothing;\n`;
}
sql += "\n";
for (const [week, theme, goal] of THEMES) {
  sql += `insert into week_themes (week_start, brand_id, theme, goal) values (${q(week)}, 'altus', ${q(theme)}, ${q(goal)}) on conflict do nothing;\n`;
}
sql += "\n";
for (const i of ITEMS) {
  const brand = BRAND[i.b];
  const c = classify(i);
  const note = NOTES.find((n) => n.d === i.d && n.b === i.b && i.kind === "post" && (!n.titleIncludes || i.t.includes(n.titleIncludes)));
  const fact = FACTS.find((f) => f.b === i.b && f.match.test(i.t));
  // Event metadata repeats the fact text, and NOTES supersede the short artifact flags.
  const brief = [fact?.brief, c.kind === "event" && fact ? null : c.brief].filter(Boolean).join(" ") || null;
  const flag = note?.flag ?? i.flag ?? null;
  const status = i.cancel ? "cancelled" : "planned";
  sql += `insert into calendar_items (brand_id, date, kind, format, pillar, title, brief, flag, status, source)
select ${q(brand)}, ${q(i.d)}, ${q(c.kind)}, ${q(c.format)}, ${q(c.pillar)}, ${q(i.t)}, ${q(brief)}, ${q(flag)}, ${q(status)}, 'artifact-import'
where not exists (select 1 from calendar_items where brand_id = ${q(brand)} and date = ${q(i.d)} and title = ${q(i.t)});\n`;
}
writeFileSync("supabase/seed.sql", sql);
console.log(`supabase/seed.sql: ${ITEMS.length} items, ${THEMES.length} themes, ${Object.keys(DEFAULT_KITS).length} brands`);
